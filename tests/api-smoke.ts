import assert from 'node:assert/strict';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';
async function main() {
const base=process.env.P2P_TEST_BASE_URL || 'http://localhost:3010';
const account=privateKeyToAccount(generatePrivateKey());
const post=async(path:string,body:unknown,opts:{cookie?:string,key?:string,origin?:string}={})=>fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json','Origin':opts.origin||base,...(opts.cookie?{'Cookie':opts.cookie}:{}),...(opts.key?{'Idempotency-Key':opts.key}:{})},body:JSON.stringify(body)});
const patch=async(path:string,body:unknown,cookie:string)=>fetch(base+path,{method:'PATCH',headers:{'Content-Type':'application/json','Origin':base,'Cookie':cookie},body:JSON.stringify(body)});
async function loginWallet(wallet:ReturnType<typeof privateKeyToAccount>) {
  const challenge=await post('/api/v1/auth/challenge',{address:wallet.address,chainId:11155111});
  assert.equal(challenge.status,200);
  const {message}=await challenge.json();
  const signature=await wallet.signMessage({message});
  const login=await post('/api/v1/auth/verify',{message,signature});
  assert.equal(login.status,200);
  const cookie=login.headers.get('set-cookie')?.split(';')[0];
  assert.ok(cookie);
  assert.ok(cookie.startsWith('peer_session='));
  return cookie;
}
const challenge=await post('/api/v1/auth/challenge',{address:account.address,chainId:11155111});
assert.equal(challenge.status,200);
const {message}=await challenge.json();
assert.match(message,/Sign in to Peer development preview/);
const signature=await account.signMessage({message});
const invalidOrigin=await post('/api/v1/auth/verify',{message,signature},{origin:'https://attacker.example'});
assert.equal(invalidOrigin.status,403);
const login=await post('/api/v1/auth/verify',{message,signature});
assert.equal(login.status,200);
const cookie=login.headers.get('set-cookie')?.split(';')[0];
assert.ok(cookie?.startsWith('peer_session='));
const replay=await post('/api/v1/auth/verify',{message,signature});
assert.equal(replay.status,401);
const denied=await post('/api/v1/orders',{adId:'eth-01',amount:'100'});
assert.equal(denied.status,401);
const before=await (await fetch(base+'/api/v1/ads')).json();
assert.ok(before.ads.every((item:Record<string,unknown>)=>!('completion' in item)&&!('trades' in item)));
const available=before.ads.find((ad:{id:string})=>ad.id==='eth-01').available;
const key='api-smoke-key-'+crypto.randomUUID();
const created=await post('/api/v1/orders',{adId:'eth-01',amount:'100'},{cookie,key});
assert.equal(created.status,201);
const order=(await created.json()).order;
assert.equal(order.state,'RESERVED');
const again=await post('/api/v1/orders',{adId:'eth-01',amount:'100'},{cookie,key});
assert.equal((await again.json()).order.id,order.id);
const conflict=await post('/api/v1/orders',{adId:'eth-01',amount:'200'},{cookie,key});
assert.equal(conflict.status,409);
const after=await (await fetch(base+'/api/v1/ads')).json();
assert.notEqual(after.ads.find((ad:{id:string})=>ad.id==='eth-01').available,available);
const mine=await fetch(base+'/api/v1/orders',{headers:{Cookie:cookie!}});
assert.equal(mine.status,200);
assert.ok((await mine.json()).orders.some((item:{id:string})=>item.id===order.id));
const cancelled=await post(`/api/v1/orders/${order.id}/cancel`,{},{cookie});
assert.equal(cancelled.status,200);
const restored=await (await fetch(base+'/api/v1/ads')).json();
assert.equal(restored.ads.find((ad:{id:string})=>ad.id==='eth-01').available,available);
const adInput={side:'buy',asset:'ETH',price:'2500',total:'1',min:'100',max:'1500',minutes:15,validHours:24};
const adCreated=await post('/api/v1/ads',adInput,{cookie});
assert.equal(adCreated.status,201);
const ad=(await adCreated.json()).ad;
assert.equal(ad.makerAddress,account.address);
const owned=await fetch(base+'/api/v1/me/ads',{headers:{Cookie:cookie!}});
assert.ok((await owned.json()).ads.some((item:{id:string})=>item.id===ad.id));
assert.equal((await post('/api/v1/orders',{adId:ad.id,amount:'1000'},{cookie,key:'self-reservation-'+crypto.randomUUID()})).status,403);
const second=privateKeyToAccount(generatePrivateKey());
const secondCookie=await loginWallet(second);
assert.equal((await patch(`/api/v1/ads/${ad.id}`,{...adInput,expectedVersion:ad.version},secondCookie)).status,404);
const otherOrderResponse=await post('/api/v1/orders',{adId:ad.id,amount:'1000'},{cookie:secondCookie,key:'maker-test-'+crypto.randomUUID()});
assert.equal(otherOrderResponse.status,201);
const otherOrder=(await otherOrderResponse.json()).order;
assert.equal(JSON.parse(otherOrder.terms_json).price,'2500');
assert.equal((await fetch(base+'/api/v1/orders/'+otherOrder.id)).status,401);
const incoming=await fetch(base+'/api/v1/me/incoming-orders',{headers:{Cookie:cookie!}});
assert.ok((await incoming.json()).orders.some((item:{id:string})=>item.id===otherOrder.id));
assert.equal((await post(`/api/v1/orders/${otherOrder.id}/respond`,{decision:'accept'},{cookie:secondCookie})).status,404);
const acceptedResponse=await post(`/api/v1/orders/${otherOrder.id}/respond`,{decision:'accept'},{cookie});
assert.equal(acceptedResponse.status,200);
assert.equal((await acceptedResponse.json()).order.state,'ACCEPTED');
const detail=await fetch(base+`/api/v1/orders/${otherOrder.id}`,{headers:{Cookie:secondCookie}});
assert.deepEqual((await detail.json()).events.map((event:{state:string})=>event.state),['RESERVED','ACCEPTED']);
const chatPath=`/api/v1/orders/${otherOrder.id}/messages`;
assert.equal((await fetch(base+chatPath)).status,401);
const outsiderCookie=await loginWallet(privateKeyToAccount(generatePrivateKey()));
assert.equal((await fetch(base+chatPath,{headers:{Cookie:outsiderCookie}})).status,404);
assert.equal((await post(chatPath,{body:'무단 메시지',clientId:crypto.randomUUID()},{cookie:outsiderCookie})).status,404);
const chatId=crypto.randomUUID();
const sent=await post(chatPath,{body:'조건 확인 부탁합니다',clientId:chatId},{cookie:secondCookie});
assert.equal(sent.status,201);
const sentBody=(await sent.json()).message;
assert.equal((await (await post(chatPath,{body:'조건 확인 부탁합니다',clientId:chatId},{cookie:secondCookie})).json()).message.id,sentBody.id);
assert.equal((await post(chatPath,{body:'연속 전송',clientId:crypto.randomUUID()},{cookie:secondCookie})).status,429);
assert.equal((await post(chatPath,{body:'확인했습니다',clientId:crypto.randomUUID()},{cookie})).status,201);
const conversation=await (await fetch(base+chatPath,{headers:{Cookie:secondCookie}})).json();
assert.deepEqual(conversation.items.filter((item:{kind:string})=>item.kind==='message').map((item:{body:string})=>item.body),['조건 확인 부탁합니다','확인했습니다']);
assert.ok(conversation.items.some((item:{kind:string;state?:string})=>item.kind==='state'&&item.state==='ACCEPTED'));
assert.equal((await post(chatPath,{body:'잘못된 출처',clientId:crypto.randomUUID()},{cookie,origin:'https://attacker.example'})).status,403);
const safetyPath=`/api/v1/orders/${otherOrder.id}/safety`;
assert.equal((await fetch(base+safetyPath)).status,401);
assert.equal((await fetch(base+safetyPath,{headers:{Cookie:outsiderCookie}})).status,404);
assert.equal((await post(safetyPath,{action:'report',reason:'SPAM',details:'반복적인 광고 메시지를 보냈습니다.'},{cookie:outsiderCookie})).status,404);
const reported=await post(safetyPath,{action:'report',reason:'SPAM',details:'반복적인 광고 메시지를 보냈습니다.'},{cookie:secondCookie});
assert.equal(reported.status,201);
const reportId=(await reported.json()).report.id;
assert.equal((await (await post(safetyPath,{action:'report',reason:'SPAM',details:'반복적인 광고 메시지를 보냈습니다.'},{cookie:secondCookie})).json()).report.id,reportId);
assert.equal((await post(safetyPath,{action:'report',reason:'FRAUD',details:'다른 내용으로 다시 신고합니다.'},{cookie:secondCookie})).status,409);
assert.equal((await (await fetch(base+safetyPath,{headers:{Cookie:cookie!}})).json()).report,null);
assert.equal((await post(safetyPath,{action:'block'},{cookie:secondCookie})).status,200);
assert.equal((await (await fetch(base+'/api/v1/ads',{headers:{Cookie:secondCookie}})).json()).ads.some((item:{id:string})=>item.id===ad.id),false);
assert.equal((await (await fetch(base+'/api/v1/ads')).json()).ads.some((item:{id:string})=>item.id===ad.id),true);
assert.equal((await post('/api/v1/orders',{adId:ad.id,amount:'100'},{cookie:secondCookie,key:'blocked-ad-test-'+crypto.randomUUID()})).status,403);
assert.equal((await fetch(base+chatPath,{headers:{Cookie:secondCookie}})).status,200);
assert.equal((await post(safetyPath,{action:'unblock'},{cookie:secondCookie})).status,200);
assert.equal((await (await fetch(base+'/api/v1/ads',{headers:{Cookie:secondCookie}})).json()).ads.some((item:{id:string})=>item.id===ad.id),true);
assert.equal((await post(`/api/v1/orders/${otherOrder.id}/respond`,{decision:'decline'},{cookie})).status,409);
const currentAd=(await (await fetch(base+'/api/v1/me/ads',{headers:{Cookie:cookie!}})).json()).ads.find((item:{id:string})=>item.id===ad.id);
assert.equal((await patch(`/api/v1/ads/${ad.id}`,{...adInput,total:'0.3',max:'500',expectedVersion:currentAd.version},cookie!)).status,409);
const editedResponse=await patch(`/api/v1/ads/${ad.id}`,{...adInput,price:'2600',total:'2',max:'2000',expectedVersion:currentAd.version},cookie!);
assert.equal(editedResponse.status,200);
const edited=(await editedResponse.json()).ad;
assert.equal(edited.available,'1.6');
assert.equal((await patch(`/api/v1/ads/${ad.id}`,{...adInput,expectedVersion:currentAd.version},cookie!)).status,409);
const pausedResponse=await patch(`/api/v1/ads/${ad.id}`,{action:'pause',expectedVersion:edited.version},cookie!);
assert.equal(pausedResponse.status,200);
const paused=(await pausedResponse.json()).ad;
assert.equal((await post('/api/v1/orders',{adId:ad.id,amount:'100'},{cookie:secondCookie,key:'paused-ad-test-'+crypto.randomUUID()})).status,404);
const resumedResponse=await patch(`/api/v1/ads/${ad.id}`,{action:'resume',expectedVersion:paused.version},cookie!);
assert.equal(resumedResponse.status,200);
const resumed=(await resumedResponse.json()).ad;
const anotherResponse=await post('/api/v1/orders',{adId:ad.id,amount:'100'},{cookie:secondCookie,key:'decline-test-'+crypto.randomUUID()});
assert.equal(anotherResponse.status,201);
const another=(await anotherResponse.json()).order;
assert.equal((await post(`/api/v1/orders/${another.id}/respond`,{decision:'decline'},{cookie})).status,200);
assert.equal((await (await fetch(base+`/api/v1/orders/${another.id}`,{headers:{Cookie:secondCookie}})).json()).order.state,'DECLINED');
const refreshedAd=(await (await fetch(base+'/api/v1/me/ads',{headers:{Cookie:cookie!}})).json()).ads.find((item:{id:string})=>item.id===ad.id);
assert.ok(refreshedAd.version>resumed.version);
const closedResponse=await patch(`/api/v1/ads/${ad.id}`,{action:'close',expectedVersion:refreshedAd.version},cookie!);
assert.equal(closedResponse.status,200);
assert.equal((await post(`/api/v1/orders/${otherOrder.id}/cancel`,{},{cookie:secondCookie})).status,200);
assert.equal((await post(chatPath,{body:'종료 후 메시지',clientId:crypto.randomUUID()},{cookie})).status,409);
assert.equal((await (await fetch(base+chatPath,{headers:{Cookie:cookie!}})).json()).writable,false);
const closedAd=(await (await fetch(base+'/api/v1/me/ads',{headers:{Cookie:cookie!}})).json()).ads.find((item:{id:string})=>item.id===ad.id);
assert.equal(closedAd.available,'2');
assert.equal(closedAd.status,'CLOSED');
assert.equal((await post('/api/v1/auth/logout',{},{cookie:secondCookie})).status,200);
assert.equal((await post('/api/v1/auth/logout',{},{cookie:outsiderCookie})).status,200);
const logout=await post('/api/v1/auth/logout',{},{cookie});
assert.equal(logout.status,200);
const oldSession=await fetch(base+'/api/v1/orders',{headers:{Cookie:cookie!}});
assert.equal(oldSession.status,401);
console.log('PASS: SIWE, ads without reputation, reservation, participant conversation and safety, stock restoration and logout.');

}
main().catch(error=>{console.error(error);process.exitCode=1;});
