  const afterReservation=store.getAd(ad.id)!;
  assert.throws(()=>store.updateAd(maker,ad.id,{...input,total:'2'},ad.version),{status:409});
  const edited=store.updateAd(maker,ad.id,{...input,price:'2100',total:'2',max:'2000'},afterReservation.version);
