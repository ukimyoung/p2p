test('closed-order retention removes messages and reports on schedule without touching active orders',()=>{
  store.resetStoreForTests();
  process.env.P2P_DB_PATH=join(testDir,'retention.sqlite');
  assert.equal((store.db().prepare('PRAGMA secure_delete').get() as {secure_delete:number}).secure_delete,1);
  const maker='0x1111111111111111111111111111111111111111';
  const taker='0x2222222222222222222222222222222222222222';
  const now=Date.now();
  const ad=store.createAd(maker,{side:'buy',asset:'ETH',price:'2000',total:'2',min:'100',max:'1500',minutes:15,validHours:24});
  const closed=String(store.reserveOrder(taker,ad.id,'100',key(50),now).id);
  const active=String(store.reserveOrder(taker,ad.id,'100',key(51),now).id);
  for(const id of [closed,active]) {
    store.postOrderMessage(taker,id,'보존 기간을 검사합니다.',crypto.randomUUID(),now);
    store.reportOrderCounterparty(taker,id,'SPAM','보존 기간을 검사하는 신고입니다.',now);
  }
  store.respondOrder(maker,closed,'decline',now+1);
  assert.deepEqual(store.pruneSensitiveOrderData(now+store.messageRetentionMs),{messages:0,reports:0});
  assert.deepEqual(store.pruneSensitiveOrderData(now+1+store.messageRetentionMs),{messages:1,reports:0});
  assert.equal(store.getOrderConversation(taker,closed).items.filter(item=>item.kind==='message').length,0);
  assert.equal(store.getOrderSafety(taker,closed).report!==null,true);
  assert.throws(()=>store.reportOrderCounterparty(maker,closed,'FRAUD','신고 접수 기한이 지났습니다.',now+1+store.reportWindowMs),{status:409});
  assert.deepEqual(store.pruneSensitiveOrderData(now+1+store.reportRetentionMs),{messages:0,reports:1});
  assert.deepEqual(store.pruneSensitiveOrderData(now+1+store.reportRetentionMs),{messages:0,reports:0});
  store.db().prepare("UPDATE order_events SET occurred_at=? WHERE order_id=? AND state='DECLINED'").run(now-store.reportWindowMs,closed);
  assert.equal(store.getOrderSafety(taker,closed).reportable,false);
  assert.equal(store.getOrderConversation(taker,active).items.filter(item=>item.kind==='message').length,1);
  assert.equal(store.getOrderSafety(taker,active).report!==null,true);
});
