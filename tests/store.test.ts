  const now=Date.now();
  const order=store.reserveOrder(taker,ad.id,'1000',key(30),now);
  const id=String(order.id);
  const clientId='11111111-1111-4111-8111-111111111111';
  assert.throws(()=>store.getOrderConversation(outsider,id),{status:404});
  assert.throws(()=>store.postOrderMessage(outsider,id,'hello',clientId,now+1),{status:404});
  assert.equal(store.getOrderConversation(maker,id).items[0].kind,'state');
  const first=store.postOrderMessage(taker,id,'  조건 확인 부탁합니다  ',clientId,now+1);
  assert.equal(first.body,'조건 확인 부탁합니다');
