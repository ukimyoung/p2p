  assert.equal(store.getMakerAds(taker).find(item=>item.id===ad.id),undefined);
  assert.throws(()=>store.updateAd(taker,ad.id,{...input,total:'2'},ad.version),{status:404});
  assert.throws(()=>store.reserveOrder(maker,ad.id,'1000',key(10)),{status:403});
